/**
 * BOOTSTRAP STEPS, in order. Each step PLANS by reading the target's current
 * state and returns only the actions still needed, so running bootstrap again
 * does nothing (idempotent). Every outside call goes through `ctx.http`
 * (stubbed in tests/bootstrap-steps.test.ts), every secret through
 * `ctx.putSecret` (never printed). Action descriptions never contain a value.
 *
 *   1 database        migrations (recorded the way the Supabase CLI records
 *                     them), then the default-tenant shell
 *   2 cloudflare      DNS for <domain> and *.<domain>, the R2 photo bucket,
 *                     the Turnstile widget (its secret -> Worker secret)
 *   3 resend          the sending domain; its DNS records into Cloudflare;
 *                     a verification request
 *   4 worker-secrets  the Worker's secrets from the operator's environment
 *                     (CRON_SECRET generated)
 *     (deploy)        CI or the dashboard's git integration
 *   5 first-admin     the first super-admin, through the deployed site's own
 *                     Setup Wizard route (provider keys optional)
 *   6 stripe-webhooks the platform and Connect endpoints; their signing
 *                     secrets -> the settings row (after the first save)
 * The Worker config itself is generated by wrangler-config.ts (bootstrap
 * writes it to bootstrap-out/<domain>/wrangler.jsonc); deploying is CI or the
 * dashboard's git integration (BOOTSTRAP-RUNBOOK.md).
 */
import type { BootstrapInputs } from './inputs.ts';

export type HttpResponse = { status: number; json: any };
export type Http = (url: string, init?: { method?: string; headers?: Record<string, string>; body?: string }) => Promise<HttpResponse>;
export type Action = { describe: string; run: () => Promise<string> };
export type StepPlan = { done: string[]; todo: Action[]; blocked?: string };
export type Ctx = {
  inputs: BootstrapInputs;
  http: Http;
  /** Read an environment value by name (secrets included; never logged). */
  env: (name: string) => string;
  /** Store a secret where it belongs (Worker secret or settings column). */
  putSecret: (place: 'worker' | 'database', name: string, value: string) => Promise<void>;
  /** Migration files in order: [name, sql]. */
  migrations: Array<[string, string]>;
  /** Run SQL on the target database (Management API, or PGlite locally). */
  sql: (query: string) => Promise<any[]>;
  random: () => string;
  /** The names (never values) of the secrets the Worker already has. */
  workerSecretNames: () => Promise<Set<string>>;
};
export type Step = { id: string; title: string; needs: string[]; plan: (ctx: Ctx) => Promise<StepPlan> };

