import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
const page = await context.newPage();
const errors = [];
page.on('console', (msg) => { const t = msg.text(); if (msg.type() === 'error' || /#418|hydrat|server rendered|didn't match|credentials/i.test(t)) errors.push('[' + msg.type() + '] ' + t); });
page.on('pageerror', (err) => errors.push('[pageerror] ' + err.message));
page.on('requestfailed', (req) => errors.push('[reqfailed] ' + req.url() + ' :: ' + (req.failure() ? req.failure().errorText : '')));
page.on('response', (res) => { if (res.status() === 404 || res.status() >= 500) errors.push('[http' + res.status() + '] ' + res.url()); });
console.log('>> Navigating with creds in URL...');
await page.goto('http://' + 'goyunir%40gmail.com' + ':' + 'goyunir-admin-dev' + '@localhost:3100/admin', { waitUntil: 'domcontentloaded', timeout: 40000 });
await page.waitForTimeout(8000);
const bodyText = (await page.evaluate(() => document.body.innerText.slice(0, 300))).replace(/\s+/g, ' ').trim();
console.log('==== BODY ====');
console.log(bodyText);
console.log('==== ERRORS ====');
console.log(errors.length ? errors.join('\n') : '(none)');
await browser.close();
